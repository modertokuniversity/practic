-- ---------------------------------------------------------------------
-- 10. time_entries — фактичні відмітки часу
--     project_id — NEW (лаб. №6-7): призначення проєкту тим самим
--     детермінованим правилом, що й PROJECTS_BY_USER у
--     src/lib/mock/attendance.ts фронтенду: для кожного розробника —
--     циклічний список "своїх" проєктів, індекс = (user_id + day_offset) % length.
--     created_by — NEW (лаб. №6-7): за замовчуванням = сам працівник (source='timer').
-- ---------------------------------------------------------------------
INSERT INTO time_entries (user_id, work_date, check_in, check_out, status, source, project_id, created_by)
SELECT
    s.user_id,
    s.work_date,
    s.planned_start + ((s.user_id * 3 + (s.work_date - DATE '2026-08-31') * 5) % 13 - 10) * interval '1 minute',
    s.planned_end   + ((s.user_id * 2 + (s.work_date - DATE '2026-08-31') * 3) % 17 - 6) * interval '1 minute',
    'completed',
    'timer',
    CASE s.user_id
        WHEN 3  THEN (ARRAY[1,2,3])[((3  + (s.work_date - DATE '2026-08-31')) % 3) + 1]
        WHEN 6  THEN (ARRAY[1,2])[((6  + (s.work_date - DATE '2026-08-31')) % 2) + 1]
        WHEN 7  THEN (ARRAY[1,3])[((7  + (s.work_date - DATE '2026-08-31')) % 2) + 1]
        WHEN 8  THEN (ARRAY[1,3])[((8  + (s.work_date - DATE '2026-08-31')) % 2) + 1]
        WHEN 9  THEN 1
